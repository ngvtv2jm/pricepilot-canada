import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const browser = await chromium.launch(process.env.PRICEPINE_CHROMIUM
  ? { executablePath: process.env.PRICEPINE_CHROMIUM, args: ['--disable-gpu', '--disable-dev-shm-usage'] }
  : {});
const origin = new URL(process.env.PRICEPINE_PREVIEW_URL || 'http://127.0.0.1:4173/').href;
if (!['localhost', '127.0.0.1'].includes(new URL(origin).hostname)) throw Error('Run this fixture test against a local preview.');
try {
  const context=await browser.newContext({viewport:{width:320,height:700},permissions:[]});
  await context.route('https://raw.githubusercontent.com/ngvtv2jm/pricepilot-canada/**',route=>route.abort());
  await context.addInitScript(()=>{
    Object.defineProperty(window, 'IntersectionObserver', { value: undefined });
    Object.defineProperty(navigator,'geolocation',{configurable:true,value:{getCurrentPosition(_,fail){fail({code:1});}}});
  });
  const page=await context.newPage();
  page.setDefaultTimeout(9000);
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(origin);
  const toggle=page.getByRole('button',{name:'Toggle navigation'});
  assert.equal(await toggle.isVisible(),true);
  const style=await toggle.evaluate(el=>({w:el.clientWidth,h:el.clientHeight,color:getComputedStyle(el).color}));
  assert.ok(style.w>=44&&style.h>=44&&style.color!=='rgb(255, 255, 255)');
  await toggle.focus();
  await toggle.press('Enter');
  assert.equal(await toggle.getAttribute('aria-expanded'),'true');
  const stores=page.getByRole('navigation').getByRole('button',{name:'Stores'});
  await stores.focus();
  await stores.press('Escape');
  assert.equal(await toggle.getAttribute('aria-expanded'),'false');
  assert.ok(await toggle.evaluate(el=>document.activeElement===el));
  await toggle.press('Space');
  await stores.click();
  await page.getByRole('heading',{name:'Find nearby branches'}).waitFor();
  assert.ok(await page.locator('main').evaluate(el=>document.activeElement===el));
  const postal=page.getByRole('textbox',{name:'Canadian postal code'});
  await postal.fill('M5V 2T');
  await page.getByRole('button',{name:'Find branches'}).click();
  await page.getByRole('alert').filter({hasText:'Enter a valid Canadian postal code'}).waitFor();
  await page.getByRole('button',{name:'Use my location'}).click();
  await page.getByRole('alert').filter({hasText:'Location permission was denied'}).waitFor();
  await postal.fill('M5V 2T6');
  await page.getByRole('button',{name:'Find branches'}).click();
  await page.getByText('Straight-line distances from the approximate centre', {exact:false}).waitFor();
  assert.ok(await page.locator('.branch-results article').count()>3);
  assert.equal(await page.evaluate(()=>localStorage.getItem('pricepilot-postal')),'M5V');
  await page.getByLabel('Search radius').selectOption('1');
  await page.getByLabel('Retailer',{exact:true}).selectOption('Giant Tiger');
  await page.getByText('No pilot branches match', {exact:false}).waitFor();
  await postal.fill('V6B 2T6');
  await page.getByRole('button',{name:'Find branches'}).click();
  await page.getByText('outside the supported Toronto pilot',{exact:false}).waitFor();
  await page.goto(origin+'#search');
  await page.locator('.product-card').first().waitFor({timeout:20000});
  const all=Number((await page.getByText(/^\d+ products$/).innerText()).split(' ')[0]);
  await page.getByRole('button', { name: 'Load more products' }).click();
  await page.getByText(/^Showing 48 of/).waitFor();
  await page.getByLabel('Retailer',{exact:true}).selectOption('Giant Tiger');
  await page.getByText(/^Showing 24 of/).waitFor();
  const filtered=Number((await page.getByText(/^\d+ products$/).innerText()).split(' ')[0]);
  assert.ok(filtered>0&&filtered<all);
  assert.equal(await page.getByLabel('Nearby branch').count(),0);
  await page.waitForFunction(() => document.querySelector('.product-card img')?.naturalWidth > 0);
  await page.locator('.product-card').first().getByRole('button',{name:'Compare sizes & prices'}).click();
  await page.getByRole('heading',{name:'Retailer website prices'}).waitFor();
  assert.equal(await page.locator('.detail select option').count(),1);
  assert.ok(await page.getByRole('link',{name:'Giant Tiger · View product'}).count()>0);
  await page.reload();
  await page.getByRole('heading',{name:'Retailer website prices'}).waitFor();
  await page.getByRole('button',{name:'Add to shopping list'}).click();
  await page.getByRole('status').filter({hasText:'Added to your shopping list'}).waitFor();
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('pricepilot-list-v2')).length),1);
  await page.setViewportSize({width:1280,height:800});
  assert.equal(await toggle.isVisible(),false);
  await page.getByRole('navigation').getByRole('button',{name:'Specifications'}).click();
  await page.getByLabel('Product 1',{exact:true}).selectOption({index:1});
  await page.getByRole('rowheader',{name:'Retailer website price'}).waitFor();
  await page.getByRole('rowheader',{name:'Verified branch price'}).waitFor();
  assert.deepEqual(errors,[]);
  const failure=await context.newPage();
  await failure.route('**/toronto-branches.json',route=>route.abort());
  await failure.goto(origin+'#stores');
  await failure.getByRole('alert').filter({hasText:'branch directory could not load'}).waitFor();
  await failure.unroute('**/toronto-branches.json');
  await failure.getByRole('button',{name:'Retry'}).click();
  await failure.getByRole('textbox',{name:'Canadian postal code'}).fill('M5V');
  await failure.getByRole('button',{name:'Find branches'}).click();
  await failure.locator('.branch-results article').first().waitFor();
  console.log({all,filtered,tests:'320px keyboard, focus and menu; desktop; postal validation, persistence and coverage; denied GPS; directory load/retry; website retailer filter; product deep link, comparison and guest list'});
} finally {
  await browser.close();
}
